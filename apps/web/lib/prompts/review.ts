export const REVIEW_CRITERIA = [
  "Subject likeness — the person(s) in the portrait must be recognizable as the same person(s) from the original, accounting for the requested art style. Key features to check: face shape, skin tone, eye color, hair color/style.",
  "Subject count — the portrait must contain the same number of PRIMARY subjects as the original photo. Minor background figures, crowds, or partially visible people in the background do NOT count as added subjects. Only fail if a completely new prominent foreground person was added or a primary subject was removed.",
  "Gender accuracy — each primary subject's apparent gender must be preserved. No gender swaps.",
  "Key accessories — glasses and distinctive facial hair from the original should be preserved (not removed entirely). Style changes, color shifts, and artistic reinterpretation of accessories are perfectly fine. Only fail if signature accessories like glasses were completely removed.",
  "Anatomical quality — no SEVERE anomalies like extra limbs, merged faces, or badly distorted facial features. Minor hand/finger imperfections, slightly awkward object interactions, and small proportional oddities are acceptable — only fail if the anatomy is clearly broken and distracting at a glance.",
] as const;

export function reviewPrompt(criteria: readonly string[], generationPrompt: string): string {
  const promptContext = `

The portrait was generated using this prompt:
---
${generationPrompt}
---

The prompt INTENTIONALLY requests style changes, clothing changes, and/or background changes. These are NOT errors — they are the goal. Your job is to catch genuine quality problems, not penalize intentional transformations.`;
  const numbered = criteria.map((c, i) => `${i + 1}. ${c}`).join("\n");
  return `You are a quality-control reviewer for AI-generated portraits.

Image 1 is the original selfie (the input photo).
Image 2 is the AI-generated portrait (the output).
${promptContext}
IMPORTANT: The output image has a decorative border/frame overlay applied AFTER generation. Any text, logos, or branding visible in the border area (edges of the image) is part of the template frame — NOT generated by the AI. Ignore all content in the border/frame area when reviewing.

Evaluate the portrait against these criteria:
${numbered}

Be generous — this is stylized AI art meant to be fun, not photo restoration. The bar is "would the subject be happy to receive this?" Only FAIL for issues that are clearly unacceptable: wrong person, wrong gender, a primary subject added/removed, or severely broken anatomy that is immediately jarring. When in doubt, PASS.

Respond with EXACTLY one of:
- PASS (if acceptable or borderline quality)
- FAIL: followed by which criteria failed and a brief explanation`;
}
